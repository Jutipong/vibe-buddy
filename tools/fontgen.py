#!/usr/bin/env python3
"""Turn a pixel TTF into a GFX font header this firmware can draw.

The firmware's draw_text() reads each glyph row padded to a byte; Adafruit's
own reader assumes rows packed continuously, so fonts generated here are meant
for that renderer only.

    python fontgen.py <font.ttf> <name> [--size 12] [--preview out.png]

Prints the glyph metrics it produced and, with --preview, draws a 400x300
mock-up of the real card screen so a font can be judged before flashing.
"""

import argparse
import os
from PIL import Image, ImageDraw, ImageFont

FIRST, LAST = 0x20, 0x7E
W, H = 400, 300


def load_glyphs(ttf, size):
    font = ImageFont.truetype(ttf, size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:
            glyphs.append({"adv": advance, "w": 0, "h": 0, "xo": 0, "yo": 0, "rows": []})
            continue
        image = Image.new("L", (w, h), 0)
        draw = ImageDraw.Draw(image)
        draw.text((-x0, -y0), ch, font=font, fill=255, anchor="la")
        image = image.point(lambda v: 255 if v >= 128 else 0)
        rows = []
        for yy in range(h):
            bits = 0
            count = 0
            for xx in range(w):
                bits = (bits << 1) | (1 if image.getpixel((xx, yy)) else 0)
                count += 1
                if count == 8:
                    rows.append(bits)
                    bits, count = 0, 0
            if count:
                rows.append(bits << (8 - count))
        glyphs.append({
            "adv": advance, "w": w, "h": h,
            "xo": x0, "yo": y0 - ascent, "rows": rows,
        })
    return glyphs, ascent + descent


def emit_header(name, glyphs, y_advance, out_path, source):
    bitmap = [byte for g in glyphs for byte in g["rows"]]
    lines = []
    lines.append("// Generated by tools/fontgen.py; do not edit.")
    lines.append(f"// Source: {source}")
    lines.append("#pragma once")
    lines.append("#include <Adafruit_GFX.h>")
    lines.append("")
    lines.append(f"static const uint8_t {name}_bitmap[] PROGMEM = {{")
    for i in range(0, len(bitmap), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 16])
        lines.append(f"  {chunk},")
    lines.append("};")
    lines.append("")
    lines.append(f"static const GFXglyph {name}_glyphs[] PROGMEM = {{")
    offset = 0
    for g in glyphs:
        lines.append(f"  {{ {offset:5d}, {g['w']:2d}, {g['h']:2d}, {g['adv']:3d}, {g['xo']:4d}, {g['yo']:4d} }},")
        offset += len(g["rows"])
    lines.append("};")
    lines.append("")
    lines.append(f"static const GFXfont {name}_font = {{")
    lines.append(f"  (uint8_t *){name}_bitmap, (GFXglyph *){name}_glyphs,")
    lines.append(f"  0x{FIRST:02X}, 0x{LAST:02X}, {y_advance}")
    lines.append("};")
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")


# --- preview -----------------------------------------------------------------

def text_width(glyphs, text, scale=1):
    total = 0
    for ch in text:
        code = ord(ch)
        if FIRST <= code <= LAST:
            total += glyphs[code - FIRST]["adv"]
    return total * scale


def draw_text(draw, glyphs, x, baseline, text, scale=1):
    cursor = 0
    for ch in text:
        code = ord(ch)
        if not (FIRST <= code <= LAST):
            code = ord("?")
        g = glyphs[code - FIRST]
        for yy in range(g["h"]):
            row_base = yy * ((g["w"] + 7) // 8)
            for xx in range(g["w"]):
                if g["rows"][row_base + (xx >> 3)] & (0x80 >> (xx & 7)):
                    px = x + (cursor + g["xo"] + xx) * scale
                    py = baseline + (g["yo"] + yy) * scale
                    if scale == 1:
                        draw.point((px, py), fill=0)
                    else:
                        draw.rectangle((px, py, px + scale - 1, py + scale - 1), fill=0)
        cursor += g["adv"]


def render_preview(glyphs, y_advance, title_scale, elapsed_scale, out_path):
    image = Image.new("L", (W, H), 255)
    draw = ImageDraw.Draw(image)
    right = 390

    # header
    draw_text(draw, glyphs, 13, 33, "NEED YOU", 2)
    label = "3 TASKS"
    draw_text(draw, glyphs, right - text_width(glyphs, label), 30, label, 1)
    draw.rectangle((12, 41, 387, 42), fill=0)

    cards = [
        ("OC", "vibe-buddy", "vibe-buddy", "NEED YOU", "1:46"),
        ("OC", "dev", "ESP32-S3-AI", "WORKING", "0:12"),
        ("OC", "open-investing", "open-investing", "WORKING", "12:30"),
    ]
    for index, (tag, title, project, state, elapsed) in enumerate(cards):
        y = 52 + index * 80
        draw.rectangle((12, y, 46, y + 22), fill=0)
        draw_text(draw, glyphs, 12 + (34 - text_width(glyphs, tag)) // 2, y + 16, tag, 1)
        baseline = y + (26 if title_scale == 2 else 20)
        draw_text(draw, glyphs, 54, baseline, title, title_scale)
        draw_text(draw, glyphs, 54, y + 52, project, 1)
        draw_text(draw, glyphs, 198, y + 50, state, 1)
        draw_text(draw, glyphs, right - text_width(glyphs, elapsed) * elapsed_scale,
                  y + (52 if elapsed_scale == 2 else 50), elapsed, elapsed_scale)
        draw.rectangle((12, y + 66, 387, y + 66), fill=0)

    image.save(out_path)
    zoom = image.resize((W * 2, H * 2), Image.NEAREST)
    zoom.save(out_path.replace(".png", "@2x.png"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("ttf")
    parser.add_argument("name")
    parser.add_argument("--size", type=int, default=12)
    parser.add_argument("--header", default=None)
    parser.add_argument("--preview", default=None)
    parser.add_argument("--title-scale", type=int, default=2)
    parser.add_argument("--elapsed-scale", type=int, default=2)
    args = parser.parse_args()

    glyphs, y_advance = load_glyphs(args.ttf, args.size)
    widths = sorted(g["adv"] for g in glyphs if g["w"])
    heights = sorted(g["h"] for g in glyphs if g["h"])
    print(f"{os.path.basename(args.ttf)} size={args.size} yAdvance={y_advance} "
          f"glyphs={len(glyphs)} adv[{widths[0]}..{widths[-1]}] h[{heights[0]}..{heights[-1]}]")

    if args.header:
        emit_header(args.name, glyphs, y_advance, args.header, os.path.basename(args.ttf))
        print(f"wrote {args.header}")
    if args.preview:
        render_preview(glyphs, y_advance, args.title_scale, args.elapsed_scale, args.preview)
        print(f"wrote {args.preview}")


if __name__ == "__main__":
    main()
